/**
 * Generates the service worker's precache manifest after the site is built.
 *
 * Caching only what a reader happens to visit is not the same as working
 * offline — it means the pages they did not think to open first are the ones
 * missing when they need them. The whole site is 104 static pages and a few
 * fonts, so it is precached outright: someone on a plane, in a hospital, or
 * with no signal gets the entire reference, not the three pages they browsed
 * before the connection dropped.
 */

import { readdir, readFile, writeFile, stat } from "node:fs/promises";
import { join, relative, resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const DIST = resolve(ROOT, "dist");
const BASE = "/dua";

async function walk(dir: string): Promise<string[]> {
  const out: string[] = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await walk(full)));
    else out.push(full);
  }
  return out;
}

const files = await walk(DIST);
const urls = files
  .map((f) => "/" + relative(DIST, f).split("\\").join("/"))
  // The service worker must not try to cache itself, and files meant for
  // crawlers and link previews are no use offline.
  .filter((u) => !["/sw.js", "/og-image.png", "/robots.txt", "/sitemap.xml"].includes(u))
  .map((u) => (u.endsWith("/index.html") ? u.slice(0, -"index.html".length) : u))
  .map((u) => BASE + u)
  .sort();

const isTr = (u: string) => u.startsWith(BASE + "/tr/");
const isPage = (u: string) => u.endsWith("/");
const COMMON = urls.filter((u) => !isPage(u) || u === BASE + "/" || u === BASE + "/tr/");
const PAGES = {
  en: urls.filter((u) => isPage(u) && !isTr(u)),
  tr: urls.filter((u) => isPage(u) && isTr(u)),
};

let bytes = 0;
for (const f of files) bytes += (await stat(f)).size;

const sw = `/*
 * Offline support. Generated by scripts/build-sw.ts — do not edit by hand.
 *
 * On install, the shared files (styles, fonts, scripts, data, both home pages)
 * are cached. The page asks for its language's pages once it is running, so a
 * reader downloads the reference in the language they read, not both.
 * Everything is served cache-first and refreshed in the background.
 */
const VERSION = ${JSON.stringify("dua-" + Date.now().toString(36))};
const COMMON = ${JSON.stringify(COMMON)};
const PAGES = ${JSON.stringify(PAGES)};

const fill = (list) =>
  caches.open(VERSION).then((c) => Promise.all(list.map((u) => c.add(u).catch(() => {}))));

self.addEventListener("install", (e) => {
  self.skipWaiting();
  e.waitUntil(fill(COMMON));
});

self.addEventListener("message", (e) => {
  const d = e.data || {};
  if (d.type === "precache" && PAGES[d.lang]) e.waitUntil(fill(PAGES[d.lang]));
});

self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== VERSION).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (e) => {
  const { request } = e;
  if (request.method !== "GET") return;
  const u = new URL(request.url);
  if (u.origin !== location.origin) return;

  e.respondWith(
    caches.match(request, { ignoreSearch: true }).then((hit) => {
      const net = fetch(request)
        .then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(VERSION).then((c) => c.put(request, copy));
          }
          return res;
        });
      if (hit) { net.catch(() => {}); return hit; }
      return net.catch(() =>
        caches.match(u.pathname.startsWith(${JSON.stringify(BASE + "/tr/")}) ? ${JSON.stringify(BASE + "/tr/")} : ${JSON.stringify(BASE + "/")}),
      );
    }),
  );
});
`;

await writeFile(resolve(DIST, "sw.js"), sw);
const size = async (list: string[]) => {
  let n = 0;
  for (const u of list) {
    const rel = u.slice(BASE.length) + (u.endsWith("/") ? "index.html" : "");
    try { n += (await stat(join(DIST, rel))).size; } catch {}
  }
  return (n / 1024 / 1024).toFixed(1);
};
console.error(
  `✓ sw.js: ${COMMON.length} shared files (${await size(COMMON)} MB) + ` +
    `${PAGES.en.length} pages per language (${await size(PAGES.en)} MB en, ${await size(PAGES.tr)} MB tr)`,
);
void bytes;
